"""CLI: ``python -m app.platform.evals {run,curve,gate,baseline,report}``.

    run      --suite synthetic|handlabeled|all --predictor deterministic|kg_learning|live_llm [--seed N] [--out F]
    curve    --suite ... [--seed N] [--sequences 8] [--length 6] [--strict-retrieval] [--out F]
    gate     [--baseline app/platform/evals/baseline.json] [--current report.json]   (exit 1 on regression)
    baseline [--out app/platform/evals/baseline.json] [--report-out F]   (regenerate from an actual run)
    report   [--out-dir reports/evals]   (deterministic + kg_learning runs and learning curves -> latest.json/md)

live_llm runs only when requested here; it needs ANTHROPIC_API_KEY and stops at
PLATFORM_EVAL_COST_CAP_USD.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from app.platform.config import PlatformSettings
from app.platform.evals.predictors import PREDICTORS
from app.platform.evals.runner import (
    BASELINE_PATH,
    REPO_ROOT,
    curve_markdown,
    gate,
    load_json,
    make_baseline,
    run_eval,
    run_learning_curve,
    run_markdown,
    write_json,
)
from app.platform.evals.synthetic import DEFAULT_SEED

SUITE_CHOICES = ("synthetic", "handlabeled", "all")


def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="python -m app.platform.evals", description="Mapping-accuracy evals")
    sub = p.add_subparsers(dest="command", required=True)

    run = sub.add_parser("run", help="run a suite through a predictor")
    run.add_argument("--suite", choices=SUITE_CHOICES, default="all")
    run.add_argument("--predictor", choices=PREDICTORS, default="deterministic")
    run.add_argument("--seed", type=int, default=DEFAULT_SEED)
    run.add_argument("--strict-retrieval", action="store_true", help="kg_learning: demo's subset pattern retrieval")
    run.add_argument("--out", type=Path)

    curve = sub.add_parser("curve", help="learning ON vs OFF over ordered sequences")
    curve.add_argument("--suite", choices=SUITE_CHOICES, default="all")
    curve.add_argument("--seed", type=int, default=DEFAULT_SEED)
    curve.add_argument("--sequences", type=int, default=8)
    curve.add_argument("--length", type=int, default=6)
    curve.add_argument("--strict-retrieval", action="store_true")
    curve.add_argument("--predictor", choices=("kg_learning", "live_llm_kg"), default="kg_learning")
    curve.add_argument("--out", type=Path)

    g = sub.add_parser("gate", help="fail (exit 1) if F1 or edits regress beyond the baseline tolerance")
    g.add_argument("--baseline", type=Path, default=BASELINE_PATH)
    g.add_argument("--current", type=Path, help="compare an existing run report instead of re-running")

    b = sub.add_parser("baseline", help="regenerate baseline.json from an actual deterministic run")
    b.add_argument("--out", type=Path, default=BASELINE_PATH)
    b.add_argument("--report-out", type=Path, default=REPO_ROOT / "reports" / "evals" / "baseline_run.json")
    b.add_argument("--seed", type=int, default=DEFAULT_SEED)

    r = sub.add_parser("report", help="write latest.json / latest.md")
    r.add_argument("--out-dir", type=Path, default=REPO_ROOT / "reports" / "evals")
    r.add_argument("--seed", type=int, default=DEFAULT_SEED)
    return p


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def build_latest(seed: int) -> tuple[dict[str, Any], str]:
    runs = {name: run_eval("all", name, seed=seed) for name in ("deterministic", "kg_learning")}
    strict = run_eval("all", "kg_learning", seed=seed, family_retrieval=False)
    curve = run_learning_curve("all", seed=seed)
    curve_strict = run_learning_curve("all", seed=seed, family_retrieval=False)
    latest: dict[str, Any] = {
        "schema_version": 1,
        "seed": seed,
        "git_sha": runs["deterministic"]["git_sha"],
        "created_at": runs["deterministic"]["created_at"],
        "runs": {**runs, "kg_learning_strict_retrieval": strict},
        "curves": {"family_retrieval": curve, "strict_retrieval": curve_strict},
    }
    md = ["# Mapping-accuracy evals (latest)", "",
          "Synthetic and hand-labeled suites are reported separately. Generated by "
          "`python -m app.platform.evals report`. live_llm was not run (opt-in, costs money).", ""]
    md += [run_markdown(runs["deterministic"]), run_markdown(runs["kg_learning"]),
           "### kg_learning with the demo's strict (subset) pattern retrieval", "",
           run_markdown(strict).split("\n", 2)[2].split("### ")[0], curve_markdown(curve), curve_markdown(curve_strict)]
    return latest, "\n".join(md)


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.command == "run":
        settings = PlatformSettings.from_env() if args.predictor.startswith("live_llm") else None
        report = run_eval(args.suite, args.predictor, seed=args.seed, settings=settings,
                          family_retrieval=not args.strict_retrieval)
        print(run_markdown(report))
        if args.out:
            write_json(args.out, report)
            print(f"wrote {args.out}")
        return 1 if report["stopped_early"] else 0
    if args.command == "curve":
        report = run_learning_curve(args.suite, seed=args.seed, n_sequences=args.sequences, length=args.length,
                                    family_retrieval=not args.strict_retrieval, predictor=args.predictor,
                                    settings=PlatformSettings.from_env() if args.predictor == "live_llm_kg" else None)
        print(curve_markdown(report))
        if args.out:
            write_json(args.out, report)
            print(f"wrote {args.out}")
        return 1 if report.get("stopped_early") else 0
    if args.command == "gate":
        baseline = load_json(args.baseline)
        if args.current:
            current = load_json(args.current)
        else:
            current = run_eval(baseline["suite"], baseline["predictor"], seed=baseline["seed"],
                               family_retrieval=baseline.get("options", {}).get("family_retrieval", True))
        failures = gate(current, baseline)
        for name, res in current["results"].items():
            m, b = res["metrics"], baseline["metrics"].get(name, {})
            print(f"{name}: F1 {m['f1']:.4f} (baseline {b.get('f1', float('nan')):.4f}), edits/case "
                  f"{m['edits_per_case']:.4f} (baseline {b.get('edits_per_case', float('nan')):.4f})")
        if failures:
            print("GATE FAILED:\n- " + "\n- ".join(failures))
            return 1
        print("gate passed")
        return 0
    if args.command == "baseline":
        report = run_eval("all", "deterministic", seed=args.seed)
        write_json(args.report_out, report)
        write_json(args.out, make_baseline(report, source=_rel(args.report_out)))
        print(f"wrote {args.out} from {args.report_out}")
        return 0
    if args.command == "report":
        latest, md = build_latest(args.seed)
        write_json(args.out_dir / "latest.json", latest)
        (args.out_dir / "latest.md").write_text(md, encoding="utf-8", newline="\n")
        print(md)
        return 0
    raise AssertionError(f"unhandled command {args.command}")


if __name__ == "__main__":
    sys.exit(main())
