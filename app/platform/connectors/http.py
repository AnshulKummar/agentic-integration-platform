"""``HttpConnector``: MCP-style tools over a real HTTP API described by OpenAPI.

Tools are generated by ``app.demo.mcp_tools.generate_tools`` (name
``<prefix>.<snake_operation_id>``; ``<prefix>_<op>`` is accepted as an alias).
A call binds args to path params, query params and the JSON body, adds auth,
and runs through the resilience policy:

* timeouts: ``settings.connector_timeout_s`` per request;
* retries (up to ``settings.connector_max_retries``) on 429/502/503/504 and on
  transport errors, with exponential backoff + jitter, honouring ``Retry-After``;
* non-idempotent requests (POST/PATCH) are retried only when the caller sent an
  ``Idempotency-Key`` (``_idempotency_key`` arg). Exception: a failure to
  *connect* is retried for any method, because no byte reached the server;
* OAuth2 client-credentials tokens are cached until shortly before expiry; a 401
  invalidates the token and the request is replayed once with a fresh one;
* ``_paginate: true`` on a GET follows ``next_cursor`` (sent back as ``cursor``)
  up to ``_max_pages`` pages (default 20, hard cap 100).

Final failures raise ``ConnectorHTTPError`` (an ``UpstreamError``) carrying the
upstream status and a short, redacted body; request headers are never included.
The spec's ``servers`` entry is ignored: the configured ``base_url`` is authoritative.
"""

from __future__ import annotations

import asyncio
import email.utils
import functools
import logging
import random
import ssl
import time
from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any
from urllib.parse import quote

import certifi
import httpx

from app.demo.mcp_tools import McpTool, generate_tools
from app.demo.openapi_diff import OpenApiError
from app.platform.config import PlatformSettings
from app.platform.errors import NotFound, PlatformError, UpstreamError, ValidationFailed
from app.platform.interfaces import ConnectorConfig, HealthStatus, SecretStore
from app.platform.observability.metrics import CONNECTOR_RETRIES
from app.platform.secrets.redaction import redact

log = logging.getLogger(__name__)

IDEMPOTENT_METHODS = frozenset({"GET", "HEAD", "PUT", "DELETE", "OPTIONS"})
RETRY_STATUSES = frozenset({429, 502, 503, 504})
DEFAULT_MAX_PAGES = 20
HARD_MAX_PAGES = 100
MAX_ERROR_BODY_CHARS = 300
#: Upstream-provided subscribe path for webhook tools (OpenAPI extension); see simulators.
SUBSCRIBE_PATH_EXT = "x-webhook-subscribe-path"
DEFAULT_SUBSCRIBE_PATH = "/webhooks"
#: Auth secret logical keys each auth kind needs.
REQUIRED_SECRETS: dict[str, tuple[str, ...]] = {
    "none": (),
    "api_key": ("api_key",),
    "bearer": ("token",),
    "oauth2_client_credentials": ("client_id", "client_secret"),
}

Sleep = Callable[[float], Awaitable[None]]


class ConnectorConfigError(PlatformError):
    status = 422
    code = "connector_misconfigured"


class UnknownTool(NotFound):
    code = "unknown_tool"


class ConnectorHTTPError(UpstreamError):
    """Final failure talking to the upstream API (after retries)."""

    def __init__(self, message: str, *, upstream_status: int | None, retryable: bool) -> None:
        super().__init__(message)
        self.upstream_status = upstream_status
        self.retryable = retryable


@functools.cache
def shared_ssl_context() -> ssl.SSLContext:
    """One verified TLS context per process (building one costs ~0.5s; connectors are built per call)."""
    return ssl.create_default_context(cafile=certifi.where())


@dataclass
class _Token:
    value: str
    expires_at: float


def parse_retry_after(value: str | None, *, now: datetime | None = None) -> float | None:
    """Seconds to wait from a ``Retry-After`` header (delta-seconds or HTTP-date)."""
    if not value:
        return None
    value = value.strip()
    try:
        return max(0.0, float(value))
    except ValueError:
        pass
    try:
        when = email.utils.parsedate_to_datetime(value)
    except (TypeError, ValueError):
        return None
    if when.tzinfo is None:
        when = when.replace(tzinfo=UTC)
    return max(0.0, (when - (now or datetime.now(UTC))).total_seconds())


def tools_from_spec(spec: dict[str, Any], prefix: str) -> list[McpTool]:
    subscribe_path = str(spec.get(SUBSCRIBE_PATH_EXT) or DEFAULT_SUBSCRIBE_PATH)
    try:
        return generate_tools(spec, prefix, subscribe_path=subscribe_path)
    except (OpenApiError, KeyError, TypeError, AttributeError) as exc:
        raise ConnectorConfigError(f"OpenAPI spec is not usable: {exc}") from exc


def tool_definition(tool: McpTool) -> dict[str, Any]:
    http = tool.annotations.get("http", {})
    return {
        **tool.mcp_definition(),
        "method": http.get("method"),
        "path": http.get("path"),
        "readOnly": bool(tool.annotations.get("readOnlyHint")),
        "deprecated": bool(tool.annotations.get("deprecated", False)),
        "webhook": tool.annotations.get("webhook"),
    }


class HttpConnector:
    """Implements ``interfaces.Connector`` against a live HTTP API."""

    def __init__(
        self,
        config: ConnectorConfig,
        secret_store: SecretStore,
        tenant_id: str,
        settings: PlatformSettings,
        transport: httpx.AsyncBaseTransport | None = None,
        *,
        sleep: Sleep = asyncio.sleep,
        clock: Callable[[], float] = time.monotonic,
        rng: random.Random | None = None,
        backoff_base_s: float = 0.25,
        backoff_max_s: float = 8.0,
        max_retry_after_s: float = 60.0,
    ) -> None:
        self.system_id = config.system_id
        self.config = config
        self.tenant_id = tenant_id
        self._store = secret_store
        self._max_retries = max(0, settings.connector_max_retries)
        self._timeout_s = settings.connector_timeout_s
        self._sleep = sleep
        self._clock = clock
        self._rng = rng or random.Random()
        self._backoff_base_s = backoff_base_s
        self._backoff_max_s = backoff_max_s
        self._max_retry_after_s = max_retry_after_s
        if config.auth.kind not in REQUIRED_SECRETS:
            raise ConnectorConfigError(f"unsupported auth kind {config.auth.kind!r}")
        prefix = config.tool_prefix or config.system_id
        self._tools: dict[str, McpTool] = {t.name: t for t in tools_from_spec(config.spec, prefix)}
        self._aliases: dict[str, str] = {name.replace(".", "_"): name for name in self._tools}
        self._token: _Token | None = None
        self._token_lock = asyncio.Lock()
        self._client = httpx.AsyncClient(
            base_url=config.base_url,
            transport=transport,
            timeout=httpx.Timeout(settings.connector_timeout_s),
            follow_redirects=False,
            verify=shared_ssl_context(),
            headers={"User-Agent": "pmaip-connector/1", "Accept": "application/json"},
        )

    def __repr__(self) -> str:
        return f"HttpConnector(system_id={self.system_id!r}, base_url={self.config.base_url!r})"

    # ----------------------------------------------------------- tools
    def tools(self) -> list[str]:
        return list(self._tools)

    def tool_definitions(self) -> list[dict[str, Any]]:
        return [tool_definition(t) for t in self._tools.values()]

    def _resolve(self, name: str) -> McpTool:
        tool = self._tools.get(name) or self._tools.get(self._aliases.get(name, ""))
        if tool is None:
            raise UnknownTool(f"{self.system_id}: unknown tool {name!r}")
        return tool

    @staticmethod
    def _bind(tool: McpTool, args: dict[str, Any]) -> tuple[str, str, dict[str, Any], dict[str, Any] | None]:
        ann = tool.annotations
        method: str = ann["http"]["method"].upper()
        path: str = ann["http"]["path"]
        for p in ann.get("pathParams", []):
            if p not in args or args[p] is None:
                raise ValidationFailed(f"{tool.name}: missing path parameter {p!r}")
            path = path.replace("{" + p + "}", quote(str(args.pop(p)), safe=""))
        query = {q: args.pop(q) for q in list(ann.get("queryParams", [])) if q in args and args[q] is not None}
        body: dict[str, Any] | None = None
        if method in ("GET", "HEAD", "DELETE", "OPTIONS"):
            query.update({k: v for k, v in args.items() if v is not None})  # pass-through filters
        elif args or ann.get("bodyFields") or ann.get("fixedBody"):
            body = {**ann.get("fixedBody", {}), **args}
        return method, path, query, body

    # ----------------------------------------------------------- calls
    async def call(self, tool: str, args: dict[str, Any]) -> Any:
        spec_tool = self._resolve(tool)
        args = dict(args or {})
        paginate = bool(args.pop("_paginate", False))
        max_pages = args.pop("_max_pages", DEFAULT_MAX_PAGES)
        idempotency_key = args.pop("_idempotency_key", None)
        method, path, query, body = self._bind(spec_tool, args)
        headers: dict[str, str] = {}
        if idempotency_key:
            headers["Idempotency-Key"] = str(idempotency_key)
        if not paginate:
            return await self._request(spec_tool.name, method, path, query, body, headers)
        if method != "GET":
            raise ValidationFailed(f"{spec_tool.name}: _paginate is only supported on GET tools")
        if not isinstance(max_pages, int) or isinstance(max_pages, bool) or not 1 <= max_pages <= HARD_MAX_PAGES:
            raise ValidationFailed(f"_max_pages must be an integer between 1 and {HARD_MAX_PAGES}")
        return await self._paginate(spec_tool.name, path, query, headers, max_pages)

    async def _paginate(
        self, tool: str, path: str, query: dict[str, Any], headers: dict[str, str], max_pages: int
    ) -> dict[str, Any]:
        items: list[Any] = []
        cursor = query.pop("cursor", None)
        pages = 0
        while True:
            page_query = {**query, **({"cursor": cursor} if cursor else {})}
            page = await self._request(tool, "GET", path, page_query, None, headers)
            pages += 1
            if not isinstance(page, dict) or not isinstance(page.get("items"), list):
                raise ConnectorHTTPError(
                    f"{self.system_id} {tool}: response is not cursor-paginated (no 'items' list)",
                    upstream_status=None,
                    retryable=False,
                )
            items.extend(page["items"])
            next_cursor = page.get("next_cursor")
            cursor = str(next_cursor) if next_cursor else None
            if cursor is None or pages >= max_pages:
                break
        return {"items": items, "next_cursor": cursor, "pages": pages, "truncated": cursor is not None}

    async def _request(
        self,
        tool: str,
        method: str,
        path: str,
        query: dict[str, Any],
        body: dict[str, Any] | None,
        headers: dict[str, str],
    ) -> Any:
        idempotent = method in IDEMPOTENT_METHODS or "Idempotency-Key" in headers
        refreshed = False
        while True:
            auth = await self._auth_headers()

            async def send(auth: dict[str, str] = auth) -> httpx.Response:
                return await self._client.request(
                    method, path, params=query or None, json=body, headers={**headers, **auth}
                )

            response = await self._send(send, idempotent=idempotent, label=f"{tool} {method} {path}")
            if response.status_code == 401 and self.config.auth.kind == "oauth2_client_credentials" and not refreshed:
                # Rejected before processing, so replaying is safe for any method.
                refreshed = True
                self._token = None
                CONNECTOR_RETRIES.labels(system=self.system_id, reason="auth_refresh").inc()
                log.info("connector %s: 401 on %s, refreshing OAuth token", self.system_id, tool)
                continue
            if response.status_code >= 400:
                raise self._http_error(tool, response)
            return self._decode(tool, response)

    async def _send(
        self, send: Callable[[], Awaitable[httpx.Response]], *, idempotent: bool, label: str
    ) -> httpx.Response:
        """One logical request with the retry policy. Returns the final response (any status)."""
        attempt = 0
        while True:
            try:
                response = await send()
            except (httpx.ConnectError, httpx.ConnectTimeout, httpx.PoolTimeout) as exc:
                # Nothing reached the server: safe to retry for every method.
                if attempt < self._max_retries:
                    await self._backoff("connect", attempt, None, label)
                    attempt += 1
                    continue
                raise ConnectorHTTPError(
                    f"{self.system_id}: cannot connect ({type(exc).__name__}) for {label}",
                    upstream_status=None,
                    retryable=True,
                ) from exc
            except httpx.TransportError as exc:
                # Timed out or broke mid-flight: the server may have acted on it.
                if idempotent and attempt < self._max_retries:
                    reason = "timeout" if isinstance(exc, httpx.TimeoutException) else "transport"
                    await self._backoff(reason, attempt, None, label)
                    attempt += 1
                    continue
                raise ConnectorHTTPError(
                    f"{self.system_id}: {type(exc).__name__} for {label}"
                    + ("" if idempotent else " (not retried: non-idempotent request without Idempotency-Key)"),
                    upstream_status=None,
                    retryable=idempotent,
                ) from exc
            if response.status_code in RETRY_STATUSES and idempotent and attempt < self._max_retries:
                retry_after = parse_retry_after(response.headers.get("Retry-After"))
                if retry_after is None or retry_after <= self._max_retry_after_s:
                    await response.aread()
                    await self._backoff(str(response.status_code), attempt, retry_after, label)
                    attempt += 1
                    continue
                log.warning("connector %s: Retry-After %.0fs exceeds cap; not retrying", self.system_id, retry_after)
            return response

    async def _backoff(self, reason: str, attempt: int, retry_after: float | None, label: str) -> None:
        if retry_after is not None:
            delay = retry_after
        else:
            ceiling = min(self._backoff_max_s, self._backoff_base_s * (2**attempt))
            delay = ceiling / 2 + self._rng.uniform(0, ceiling / 2)  # "equal jitter"
        CONNECTOR_RETRIES.labels(system=self.system_id, reason=reason).inc()
        log.info(
            "connector %s: retry %d for %s after %s, sleeping %.2fs",
            self.system_id,
            attempt + 1,
            label,
            reason,
            delay,
        )
        await self._sleep(delay)

    def _http_error(self, tool: str, response: httpx.Response) -> ConnectorHTTPError:
        snippet = redact(response.text[:MAX_ERROR_BODY_CHARS].replace("\n", " ")) if response.content else ""
        return ConnectorHTTPError(
            f"{self.system_id} {tool} failed: HTTP {response.status_code}" + (f": {snippet}" if snippet else ""),
            upstream_status=response.status_code,
            retryable=response.status_code in RETRY_STATUSES,
        )

    def _decode(self, tool: str, response: httpx.Response) -> Any:
        if not response.content:
            return None
        if "json" in response.headers.get("content-type", ""):
            try:
                return response.json()
            except ValueError as exc:
                raise ConnectorHTTPError(
                    f"{self.system_id} {tool}: invalid JSON response",
                    upstream_status=response.status_code,
                    retryable=False,
                ) from exc
        return response.text

    # ----------------------------------------------------------- auth
    async def _secret(self, logical: str) -> str:
        name = self.config.auth.secrets.get(logical)
        if not name:
            raise ConnectorConfigError(f"{self.system_id}: auth secret {logical!r} is not configured")
        try:
            return await self._store.reveal(self.tenant_id, name)
        except NotFound as exc:
            raise ConnectorConfigError(f"{self.system_id}: secret {name!r} does not exist") from exc

    async def _auth_headers(self) -> dict[str, str]:
        auth = self.config.auth
        if auth.kind == "api_key":
            return {auth.header_name: await self._secret("api_key")}
        if auth.kind == "bearer":
            return {"Authorization": f"Bearer {await self._secret('token')}"}
        if auth.kind == "oauth2_client_credentials":
            return {"Authorization": f"Bearer {await self._access_token()}"}
        return {}

    async def _access_token(self) -> str:
        async with self._token_lock:
            token = self._token
            if token is not None and self._clock() < token.expires_at:
                return token.value
            self._token = await self._fetch_token()
            return self._token.value

    async def _fetch_token(self) -> _Token:
        auth = self.config.auth
        if not auth.token_url:
            raise ConnectorConfigError(f"{self.system_id}: oauth2 token_url is not configured")
        client_id = await self._secret("client_id")
        client_secret = await self._secret("client_secret")
        form = {"grant_type": "client_credentials"}
        if auth.scopes:
            form["scope"] = " ".join(auth.scopes)

        async def send() -> httpx.Response:
            # client_secret_basic (RFC 6749 section 2.3.1); relative token_url resolves against base_url.
            return await self._client.post(auth.token_url or "", data=form, auth=(client_id, client_secret))

        response = await self._send(send, idempotent=True, label="oauth token")
        if response.status_code != 200:
            raise self._http_error("oauth_token", response)
        try:
            payload = response.json()
            value = str(payload["access_token"])
            expires_in = float(payload.get("expires_in", 3600))
        except (ValueError, KeyError, TypeError) as exc:
            raise ConnectorHTTPError(
                f"{self.system_id}: malformed token response", upstream_status=response.status_code, retryable=False
            ) from exc
        skew = min(30.0, expires_in * 0.1)
        log.info("connector %s: obtained OAuth token (expires in %.0fs)", self.system_id, expires_in)
        return _Token(value=value, expires_at=self._clock() + max(0.0, expires_in - skew))

    # ----------------------------------------------------------- health / lifecycle
    async def health(self) -> HealthStatus:
        started = time.perf_counter()
        try:
            response = await self._client.get(self.config.health_path, timeout=min(5.0, self._timeout_s))
        except httpx.HTTPError as exc:
            latency = (time.perf_counter() - started) * 1000
            log.warning("connector %s health probe failed: %s", self.system_id, type(exc).__name__)
            return HealthStatus(ok=False, latency_ms=latency, detail=type(exc).__name__)
        latency = (time.perf_counter() - started) * 1000
        ok = 200 <= response.status_code < 300
        return HealthStatus(ok=ok, latency_ms=latency, detail=f"HTTP {response.status_code}")

    async def aclose(self) -> None:
        await self._client.aclose()

    async def __aenter__(self) -> HttpConnector:
        return self

    async def __aexit__(self, *_exc: object) -> None:
        await self.aclose()
